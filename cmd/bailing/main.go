// Command bailing is the 百灵 photo & music server.
//
//	bailing serve               start the web server
//	bailing user add NAME [--admin] [--display "Mom"]
//	bailing user list | passwd NAME | del NAME
//	bailing scan [photos|music|all]
//	bailing version
//
// Every sub command accepts -config PATH (default: $BAILING_CONFIG or ./config.yaml).
package main

import (
	"bufio"
	"context"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"

	"bailing/internal/app"
	"bailing/internal/config"
	"bailing/internal/httpapi"

	"golang.org/x/term"
)

// version is set at build time: -ldflags "-X main.version=v0.1.0"
var version = "dev"

func main() {
	if len(os.Args) < 2 {
		usage()
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "serve":
		err = cmdServe(os.Args[2:])
	case "user":
		err = cmdUser(os.Args[2:])
	case "scan":
		err = cmdScan(os.Args[2:])
	case "version", "-v", "--version":
		fmt.Println("bailing", version)
	case "help", "-h", "--help":
		usage()
	default:
		usage()
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func usage() {
	fmt.Fprint(os.Stderr, `bailing - photo albums & music for the family

Usage:
  bailing serve                         [-config config.yaml]
  bailing user add NAME [--admin] [--display NAME]
  bailing user list
  bailing user passwd NAME
  bailing user del NAME
  bailing scan [photos|music|all]
  bailing version
`)
}

// parseInterleaved lets flags appear before or after positional arguments
// (Go's flag package normally stops at the first positional one).
func parseInterleaved(fs *flag.FlagSet, args []string) ([]string, error) {
	var pos []string
	for {
		if err := fs.Parse(args); err != nil {
			return nil, err
		}
		if fs.NArg() == 0 {
			return pos, nil
		}
		pos = append(pos, fs.Arg(0))
		args = fs.Args()[1:]
	}
}

func defaultConfigPath() string {
	if p := os.Getenv("BAILING_CONFIG"); p != "" {
		return p
	}
	return "config.yaml"
}

func loadApp(cfgPath string) (*app.App, error) {
	cfg, err := config.Load(cfgPath)
	if err != nil {
		return nil, err
	}
	level := slog.LevelInfo
	switch strings.ToLower(cfg.LogLevel) {
	case "debug":
		level = slog.LevelDebug
	case "warn":
		level = slog.LevelWarn
	case "error":
		level = slog.LevelError
	}
	log := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: level}))
	return app.New(cfg, log, version)
}

func cmdServe(args []string) error {
	fs := flag.NewFlagSet("serve", flag.ExitOnError)
	cfgPath := fs.String("config", defaultConfigPath(), "config file")
	if _, err := parseInterleaved(fs, args); err != nil {
		return err
	}
	a, err := loadApp(*cfgPath)
	if err != nil {
		return err
	}
	defer a.Close()

	handler, err := httpapi.New(a)
	if err != nil {
		return err
	}
	srv := &http.Server{
		Addr:              a.Cfg.Server.Listen,
		Handler:           handler,
		ReadHeaderTimeout: 10 * time.Second,
		IdleTimeout:       120 * time.Second,
		// no WriteTimeout: audio streams may legitimately run for a long time
	}
	a.Start()

	errCh := make(chan error, 1)
	go func() {
		a.Log.Info("listening", "addr", srv.Addr, "base_path", a.Cfg.Server.BasePath, "version", version)
		errCh <- srv.ListenAndServe()
	}()

	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt, syscall.SIGTERM)
	select {
	case err := <-errCh:
		if !errors.Is(err, http.ErrServerClosed) {
			return err
		}
	case s := <-sig:
		a.Log.Info("shutting down", "signal", s.String())
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		srv.Shutdown(ctx)
	}
	return nil
}

func cmdScan(args []string) error {
	fs := flag.NewFlagSet("scan", flag.ExitOnError)
	cfgPath := fs.String("config", defaultConfigPath(), "config file")
	pos, err := parseInterleaved(fs, args)
	if err != nil {
		return err
	}
	what := "all"
	if len(pos) > 0 {
		what = pos[0]
	}
	a, err := loadApp(*cfgPath)
	if err != nil {
		return err
	}
	defer a.Close()
	a.Scan(what)
	// thumbnails continue in the running server; the CLI only indexes.
	fmt.Println("scan finished; thumbnails are generated by the running server in the background")
	return nil
}

func cmdUser(args []string) error {
	fs := flag.NewFlagSet("user", flag.ExitOnError)
	cfgPath := fs.String("config", defaultConfigPath(), "config file")
	admin := fs.Bool("admin", false, "grant admin rights (add)")
	display := fs.String("display", "", "display name (add)")
	pos, err := parseInterleaved(fs, args)
	if err != nil {
		return err
	}
	if len(pos) == 0 {
		usage()
		return errors.New("missing user sub command")
	}
	a, err := loadApp(*cfgPath)
	if err != nil {
		return err
	}
	defer a.Close()

	need := func() (string, error) {
		if len(pos) < 2 {
			return "", errors.New("missing NAME")
		}
		return pos[1], nil
	}
	switch pos[0] {
	case "add":
		name, err := need()
		if err != nil {
			return err
		}
		pw, err := readPassword()
		if err != nil {
			return err
		}
		if err := a.Auth.AddUser(name, *display, pw, *admin); err != nil {
			return err
		}
		fmt.Printf("user %q created (admin=%v)\n", name, *admin)
	case "passwd":
		name, err := need()
		if err != nil {
			return err
		}
		pw, err := readPassword()
		if err != nil {
			return err
		}
		if err := a.Auth.SetPassword(name, pw); err != nil {
			return err
		}
		fmt.Printf("password of %q changed; existing sessions were signed out\n", name)
	case "del", "delete", "rm":
		name, err := need()
		if err != nil {
			return err
		}
		if err := a.Auth.DeleteUser(name); err != nil {
			return err
		}
		fmt.Printf("user %q deleted\n", name)
	case "list", "ls":
		users, err := a.Auth.ListUsers()
		if err != nil {
			return err
		}
		for _, u := range users {
			role := ""
			if u.IsAdmin {
				role = " (admin)"
			}
			fmt.Printf("%-16s %s%s\n", u.Name, u.DisplayName, role)
		}
	default:
		return fmt.Errorf("unknown user sub command %q", pos[0])
	}
	return nil
}

// readPassword prompts twice on a terminal, or reads one line from stdin
// (so `echo secret | bailing user add mom` works in scripts).
func readPassword() (string, error) {
	fd := int(os.Stdin.Fd())
	if !term.IsTerminal(fd) {
		line, err := bufio.NewReader(os.Stdin).ReadString('\n')
		if err != nil && line == "" {
			return "", err
		}
		return strings.TrimRight(line, "\r\n"), nil
	}
	fmt.Fprint(os.Stderr, "Password: ")
	p1, err := term.ReadPassword(fd)
	fmt.Fprintln(os.Stderr)
	if err != nil {
		return "", err
	}
	fmt.Fprint(os.Stderr, "Repeat:   ")
	p2, err := term.ReadPassword(fd)
	fmt.Fprintln(os.Stderr)
	if err != nil {
		return "", err
	}
	if string(p1) != string(p2) {
		return "", errors.New("passwords do not match")
	}
	return string(p1), nil
}
